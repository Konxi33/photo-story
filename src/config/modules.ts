const byId = new Map(MODULES.map((m) => [m.id, m]));

export function getModule(id: string): ModuleDoc | undefined {
  return byId.get(id);
}

/** 侧栏/命令面板用的一句话说明 */
export function moduleTagline(href: string): string {
  const found = MODULES.find((m) => m.href === href);
  return found?.tagline ?? '';
}
